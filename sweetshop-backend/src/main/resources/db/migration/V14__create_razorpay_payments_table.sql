-- One row per Razorpay order this shop creates. Razorpay's signature only proves "this Razorpay order
-- was paid"; this row is what ties that order to the customer who started it and the exact amount they
-- were asked to pay, and records which shop order (if any) it has already paid for.
CREATE TABLE razorpay_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razorpay_order_id VARCHAR(100) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    order_id BIGINT UNIQUE REFERENCES orders(id),
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_razorpay_payments_user_id ON razorpay_payments(user_id);
